import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.stats import pearsonr, spearmanr

print("Практика 16. Варіант 1 — Київ")

alpha = 0.05
np.random.seed(1)
city = "Київ"
monthly_temp = [-4, -3, 2, 9, 15, 19, 21, 20, 14, 8, 2, -2]
months = ["Січ", "Лют", "Бер", "Кві", "Тра", "Чер", "Лип", "Сер", "Вер", "Жов", "Лис", "Гру"]

rows = []
for month, temp in zip(months, monthly_temp):
    heating_days = np.clip(18 - temp + np.random.normal(0, 1.5), 0, 30)
    heating_days = round(heating_days)
    cost = 0.15 * heating_days + np.random.normal(0, 1.0)
    cost = round(max(cost, 0), 1)
    rows.append({
        "місто": city, "місяць": month, "температура": temp,
        "опалювальні_дні": heating_days, "витрати_на_опалення": cost,
    })

climate = pd.DataFrame(rows)
print(climate)

print("\nЗавдання 1")
fig, ax = plt.subplots(figsize=(6, 4))
ax.scatter(climate["температура"], climate["витрати_на_опалення"])
ax.set_xlabel("Середньомісячна температура, °C")
ax.set_ylabel("Витрати на опалення, тис. грн")
ax.set_title("Витрати на опалення залежно від температури, Київ")
plt.show()
print("Хмара точок приблизно лінійна з від'ємним нахилом: що тепліше, то менші витрати. Через шум у витратах (std = 1 тис. грн) розкид навколо прямої помітний, а в теплі місяці витрати впираються в нуль (код обрізає від'ємні значення через max(cost, 0)), тому праворуч хмара трохи сплощена. Явних викидів немає. Це узгоджується з кодом: опалювальні дні ≈ 18 − температура, а витрати ≈ 0.15 · опалювальні дні, тобто витрати лінійно спадають з температурою.")

print("\nЗавдання 2")
r = pearsonr(climate["температура"], climate["витрати_на_опалення"])
rho = spearmanr(climate["температура"], climate["витрати_на_опалення"])
print(f"Пірсон: r = {r.statistic:.3f}, p = {r.pvalue:.2e}")
print(f"Спірмен: rho = {rho.statistic:.3f}, p = {rho.pvalue:.2e}")
for name, res in [("Пірсона", r), ("Спірмена", rho)]:
    if res.pvalue < alpha:
        print(f"Для коефіцієнта {name}: p < 0.05 → відхиляємо H0 'справжня кореляція = 0', зв'язок статистично значущий.")
    else:
        print(f"Для коефіцієнта {name}: p ≥ 0.05 → немає підстав відхилити H0 'справжня кореляція = 0'.")
print(f"Різниця |r − rho| = {abs(r.statistic - rho.statistic):.3f}. Коефіцієнти близькі, бо зв'язок монотонний і майже лінійний без викидів — у такому разі Пірсон і Спірмен узгоджуються. Спірмен трохи сильніший, бо нульові витрати влітку порушують лінійність (на що реагує Пірсон), але не монотонність.")
ci = r.confidence_interval(confidence_level=0.95)
print(f"95% ДІ для r: ({ci.low:.3f}, {ci.high:.3f})")
print("Процедура побудови такого інтервалу в 95% повторень накриває справжню кореляцію генеральної сукупності. Інтервал повністю від'ємний і далекий від нуля, тобто дані узгоджуються лише з сильним від'ємним зв'язком; ширина інтервалу показує невизначеність через малу вибірку (n = 12).")

print("\nЗавдання 3")
three = climate[["температура", "опалювальні_дні", "витрати_на_опалення"]]
corr_p = three.corr()
corr_s = three.corr(method="spearman")
print(corr_p.round(3))
pairs = corr_p.where(np.triu(np.ones(corr_p.shape, dtype=bool), k=1)).stack().abs()
print(f"Найсильніша пара: {pairs.idxmax()} (|r| = {pairs.max():.3f}); найслабша: {pairs.idxmin()} (|r| = {pairs.min():.3f}).")
print("Це очікувано: опалювальні дні напряму обчислені з температури з малим шумом, тому ця пара корелює найсильніше. Витрати отримані з опалювальних днів з додатковим, відносно великим шумом, тож їхні зв'язки слабші.")
print(corr_s.round(3))
print("З методом Спірмена значення трохи змінюються, але порядок пар за силою зв'язку і висновки ті самі — зв'язки монотонні й без викидів.")

print("\nЗавдання 4")
print("Тут зв'язок прямий і детермінований кодом: heating_days = 18 − temp + шум, cost = 0.15 · heating_days + шум. Отже температура (через кількість опалювальних днів) справді спричиняє зміну витрат — у цих даних це причинність, закладена формулою, а не випадковий збіг. На відміну від прикладу 'морозиво й утоплення', де обидві змінні залежать від третьої (спека), тут немає конфаундера: опалювальні дні — не спільна причина, а проміжна ланка (медіатор) ланцюга температура → опалювальні дні → витрати. Але сама кореляція цього не доводить — ми знаємо це лише тому, що бачимо код генерації; на реальних даних висновок про причинність потребує додаткових аргументів.")

print("\nЗавдання 5")
anomaly = pd.DataFrame([{
    "місто": city, "місяць": "Лип*", "температура": 21,
    "опалювальні_дні": 0, "витрати_на_опалення": round(climate["витрати_на_опалення"].max() * 5, 1),
}])
print("Аварія на котельні в липні: аварійне перезапускання системи і закупівля резервного палива дали витрати, у 5 разів більші за максимальні місячні.")
climate_a = pd.concat([climate, anomaly], ignore_index=True)
print(climate_a.tail(3))
r_a = pearsonr(climate_a["температура"], climate_a["витрати_на_опалення"])
rho_a = spearmanr(climate_a["температура"], climate_a["витрати_на_опалення"])
print(f"Пірсон: було {r.statistic:.3f}, стало {r_a.statistic:.3f} (зміна {r_a.statistic - r.statistic:+.3f})")
print(f"Спірмен: було {rho.statistic:.3f}, стало {rho_a.statistic:.3f} (зміна {rho_a.statistic - rho.statistic:+.3f})")
print("Пірсон змінився значно сильніше. Він використовує самі значення і квадрати відхилень від середнього, тому одна точка з величезним відхиленням домінує в чисельнику й знаменнику і 'тягне' коефіцієнт. Спірмен працює з рангами: аномальне значення отримує просто найбільший ранг (13), і його вплив обмежений, хоч би яким великим було саме число.")

