import pandas as pd

print("Практика 3. Варіант 1 — Київ")

print("\nЗавдання 1")
months = ["Січ", "Лют", "Бер", "Кві", "Тра", "Чер", "Лип", "Сер", "Вер", "Жов", "Лис", "Гру"]
values = [78, 74, 68, 58, 50, 44, 40, 42, 52, 66, 76, 82]
wide = pd.DataFrame([["Київ"] + values], columns=["місто"] + months)
print(wide)
print(wide.shape)

print("\nЗавдання 2")
tidy = wide.melt(id_vars="місто", var_name="місяць", value_name="хмарність")
print(tidy)
print(tidy.shape)
print("12 рядків, бо кожен із 12 стовпців-місяців став окремим спостереженням (місто, місяць, хмарність), а назви стовпців перейшли у значення стовпця 'місяць'.")

print("\nЗавдання 3")
print("місто — номінальна шкала: назви лише розрізняють об'єкти, без порядку.")
print("місяць — порядкова шкала: місяці мають природний порядок, але немає змістовного нуля, а як назви вони не підтримують арифметики.")
print("хмарність — шкала відношень: є абсолютний нуль (0% — повна відсутність хмар), і відношення мають зміст (80% удвічі більше за 40%).")

print("\nЗавдання 4")
back = tidy.pivot(index="місто", columns="місяць", values="хмарність")
back = back[months].reset_index()
back.columns.name = None
print(back)
print("Збігається з оригіналом:", back.equals(wide))

print("\nЗавдання 5")
tidy.to_csv("variant.csv", index=False)
tidy.to_json("variant.json", orient="records", force_ascii=False)
reloaded_csv = pd.read_csv("variant.csv")
reloaded_json = pd.read_json("variant.json")
print("CSV збігся:", reloaded_csv.equals(tidy))
print("JSON збігся:", reloaded_json.equals(tidy))
print(open("variant.csv", encoding="utf-8").read())
print(open("variant.json", encoding="utf-8").read())
print("CSV — один рядок заголовків і далі рядки значень через кому, назви полів записані один раз. JSON (records) — список об'єктів, де кожен запис містить пари 'ключ: значення', тобто назви полів повторюються в кожному записі, а типи (число/рядок) зберігаються явно.")

print("""
Відповіді на питання:
1. 'місто' — лише мітка, яка розрізняє об'єкти; міста не можна впорядкувати чи відняти одне від одного, тому шкала номінальна. 'Хмарність' має абсолютний нуль (0% — небо без хмар), тож різниці й відношення змістовні — це шкала відношень.
2. У wide-таблиці змінна 'місяць' захована в назвах стовпців, а один рядок містить 12 спостережень. Tidy вимагає: кожна змінна — стовпець, кожне спостереження — рядок. Після melt() місяць стає окремим стовпцем, а кожне вимірювання — окремим рядком.
3. CSV — плоский текст із роздільником, без типів і вкладеності, назви стовпців лише в заголовку. JSON — структурований формат із ключами в кожному записі, підтримує вкладені структури й явно розрізняє числа, рядки та null; він більший за обсягом, але самоописовий.
""")
