import numpy as np
from scipy import stats

print("Практика 13. Варіант 1 — Київ, липень 21°C, стара норма μ0 = 20.0°C")

july_temp = 21
mu0 = 20.0
alpha = 0.05

print("\nЗавдання 1")
np.random.seed(1)
daily_temps = np.random.normal(loc=july_temp, scale=2.5, size=30)
print(np.round(daily_temps, 2))
x_bar = daily_temps.mean()
s = daily_temps.std(ddof=1)
n = len(daily_temps)
print(f"x̄ = {x_bar:.3f}, s = {s:.3f}")

print("\nЗавдання 2")
print("H0: μ = 20.0°C (стара норма липня в Києві досі відповідає дійсності)")
print("H1: μ ≠ 20.0°C (середня липнева температура відрізняється від старої норми)")
print("Обрано двобічний тест: питання сформульоване як 'чи норма більше не відповідає дійсності', а зміна можлива в будь-який бік. Вибір зроблено до обчислень, щоб не підлаштовувати тест під отримане x̄.")

print("\nЗавдання 3")
se = s / np.sqrt(n)
z = (x_bar - mu0) / se
p_value = 2 * (1 - stats.norm.cdf(abs(z)))
print(f"se = {se:.4f}, z = {z:.3f}, p-value = {p_value:.4f}")

print("\nЗавдання 4")
if p_value < alpha:
    print(f"p = {p_value:.4f} < 0.05 → відхиляємо H0.")
    direction = "вища" if x_bar > mu0 else "нижча"
    print(f"Наявні дані дають статистично значущі підстави вважати, що середня липнева температура в Києві ({x_bar:.2f}°C) {direction} за стару довідникову норму 20.0°C (z = {z:.2f}, p ≈ {p_value:.3f}, двобічний тест, α = 0.05).")
else:
    print(f"p = {p_value:.4f} ≥ 0.05 → не відхиляємо H0.")
    print(f"Наявні дані не дають статистично значущих підстав вважати, що середня липнева температура в Києві відрізняється від старої норми 20.0°C (x̄ = {x_bar:.2f}°C, z = {z:.2f}, p ≈ {p_value:.3f}, двобічний тест, α = 0.05).")

print("\nЗавдання 5")
ci_low, ci_high = x_bar - 1.96 * se, x_bar + 1.96 * se
inside = ci_low <= mu0 <= ci_high
print(f"95% ДІ: ({ci_low:.3f}, {ci_high:.3f}); μ0 = 20.0 у інтервалі: {inside}")
print("Висновки узгоджуються:", inside == (p_value >= alpha))
print("Помилка I роду: визнати, що липень у Києві змінився, і переписати довідник, коли стара норма 20.0°C насправді ще правильна — у довіднику з'явиться хибна нова норма.")
print("Помилка II роду: залишити стару норму, коли клімат Києва насправді вже потеплішав — довідник застаріє, і на нього спиратимуться розрахунки енергоспоживання, сільського господарства, будівельні норми.")
print("Для кліматологів, що готують офіційний довідник, дорожчою зазвичай вважають помилку I роду: офіційну норму змінюють рідко, і зміна без надійних доказів підриває довіру й спричиняє каскад змін у нормативах. Тому α беруть малим. Проте тривала помилка II роду теж шкодить, тому висновок підтверджують даними за багато років.")

print("""
Відповіді на питання:
1. p-value — це ймовірність отримати таке або ще більше відхилення x̄ від 20.0°C, якщо H0 істинна (норма правильна). Це ймовірність даних за умови гіпотези, а не ймовірність гіпотези за даними, тому вона не є 'ймовірністю, що μ0 правильна'.
2. Якщо обирати тип тесту після того, як побачено x̄, можна завжди взяти однобічний у 'вигідний' бік і вдвічі зменшити p-value. Це підвищує реальну ймовірність помилки I роду вище заявленого α, і висновок стає недостовірним.
3. Помилка I роду — визнати зміну клімату Києва, коли її немає (хибна тривога). Помилка II роду — не помітити зміну, яка вже сталася (пропуск). Вони стосуються різних станів реальності й мають різні наслідки, а зменшення однієї при фіксованому n збільшує іншу.
4. Так, висновки узгодилися. При тому самому α двобічний тест відхиляє H0 тоді й лише тоді, коли μ0 лежить поза (1-α) довірчим інтервалом, бо обидва спираються на ту саму величину |x̄ - μ0|/se і той самий критичний поріг 1.96.
""")
