import numpy as np
import pandas as pd
from scipy import stats

print("Практика 12. Варіант 1 — Київ, липнева температура 21°C")

july_temp = 21

print("\nЗавдання 1")
np.random.seed(1)
daily_temps = np.random.normal(loc=july_temp, scale=2.5, size=30)
print(np.round(daily_temps, 2))
mean = daily_temps.mean()
s = daily_temps.std(ddof=1)
n = len(daily_temps)
print(f"mean = {mean:.3f}, s (ddof=1) = {s:.3f}")

print("\nЗавдання 2")
se = s / np.sqrt(n)
ci95 = stats.t.interval(0.95, df=n - 1, loc=mean, scale=se)
print(f"se = {se:.4f}")
print(f"95% ДІ для середнього: ({ci95[0]:.3f}, {ci95[1]:.3f})")
print("z-значення можна використовувати лише за відомого σ генеральної сукупності (або дуже великого n). Тут σ невідоме, ми оцінюємо його через s, і ця оцінка сама має похибку; t-розподіл із n-1 = 29 ступенями свободи має важчі хвости і враховує цю додаткову невизначеність.")

print("\nЗавдання 3")
above = daily_temps > july_temp
p_hat = above.mean()
n_p, n_1p = n * p_hat, n * (1 - p_hat)
print(f"p_hat = {p_hat:.4f}, n·p = {n_p:.1f}, n·(1-p) = {n_1p:.1f}")
print("Обидва значення ≥ 5" if min(n_p, n_1p) >= 5 else "Одне зі значень < 5 — нормальне наближення ненадійне")
se_p = np.sqrt(p_hat * (1 - p_hat) / n)
ci_p = stats.norm.interval(0.95, loc=p_hat, scale=se_p)
print(f"95% ДІ для частки: ({ci_p[0]:.3f}, {ci_p[1]:.3f})")
covers = ci_p[0] <= 0.5 <= ci_p[1]
print("0.5 потрапляє в інтервал:", covers)
if covers:
    print("Інтервал накрив теоретичне значення 0.5, як і мало статися для ~95% вибірок.")
else:
    print("Інтервал не накрив 0.5. Це можливо: процедура 95% довіри гарантує накриття лише для 95% вибірок, а 5% вибірок дають інтервали, що не містять справжнього значення. Наша конкретна вибірка з 30 днів могла випадково виявитися серед них.")

print("\nЗавдання 4")
rows = []
for level in [0.90, 0.95, 0.99]:
    lo, hi = stats.t.interval(level, df=n - 1, loc=mean, scale=se)
    rows.append({"рівень": f"{int(level * 100)}%", "нижня": lo, "верхня": hi, "ширина": hi - lo})
print(pd.DataFrame(rows).round(3))
print("Ширина зростає 90% → 95% → 99%, бо вищий рівень довіри вимагає більшого критичного значення t: щоб частіше накривати справжнє значення, інтервал має бути ширшим. Щоб звузити 99% інтервал, треба 'заплатити' розміром вибірки n: se = s/√n зменшується з ростом n.")

print("\nЗавдання 5")
print(f"Інтервал ({ci95[0]:.2f}, {ci95[1]:.2f}) °C отримано процедурою, яка в 95% випадків накриває справжню середню температуру. Якби ми згенерували ще 100 таких вибірок по 30 днів і для кожної побудували інтервал тим самим способом, приблизно 95 із них містили б справжнє середнє, а близько 5 — ні. Для цього конкретного інтервалу ми не знаємо, чи він серед 'вдалих'; 95% — характеристика методу, а не ймовірність для одного вже обчисленого інтервалу.")

print("""
Відповіді на питання:
1. Точкова оцінка — одне число (x̄), яке майже напевно не дорівнює справжньому параметру і нічого не каже про свою точність. Довірчий інтервал додає діапазон правдоподібних значень і показує, наскільки оцінка невизначена.
2. Коли σ невідоме, його замінюють на вибіркове s, яке теж випадкове. Статистика (x̄ - μ)/(s/√n) має t-розподіл з n-1 ступенями свободи, що має важчі хвости, ніж нормальний. Для малих і середніх n використання z дало б занадто вузький інтервал.
3. 95% довіри означає, що процедура побудови інтервалу в 95% повторень накриває справжній параметр. Справжній параметр — фіксоване число, а не випадкова величина: конкретний інтервал його або містить, або ні, тому говорити про 'ймовірність 95% для цього інтервалу' некоректно.
4. Ширина залежить від: рівня довіри (вищий — ширше), розкиду даних s (більший — ширше) і розміру вибірки n (більший — вужче, пропорційно 1/√n).
""")
