import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.stats import linregress, pearsonr

print("Практика 17. Варіант 1 — Київ")

np.random.seed(1)
city = "Київ"
monthly_temp = [-4, -3, 2, 9, 15, 19, 21, 20, 14, 8, 2, -2]
months = ["Січ", "Лют", "Бер", "Кві", "Тра", "Чер", "Лип", "Сер", "Вер", "Жов", "Лис", "Гру"]

rows = []
for month, temp in zip(months, monthly_temp):
    heating_days = np.clip(18 - temp + np.random.normal(0, 1.5), 0, 30)
    heating_days = round(heating_days)
    cost = 0.15 * heating_days + np.random.normal(0, 1.0)
    cost = round(max(cost, 0), 1)
    rows.append({
        "місто": city, "місяць": month, "температура": temp,
        "опалювальні_дні": heating_days, "витрати_на_опалення": cost,
    })

climate = pd.DataFrame(rows)
print(climate)
x = climate["температура"]
y = climate["витрати_на_опалення"]

print("\nЗавдання 1")
result = linregress(x, y)
b0, b1 = result.intercept, result.slope
print(f"slope = {b1:.3f}, intercept = {b0:.3f}, p = {result.pvalue:.2e}")
print(f"Рівняння: витрати ≈ {b0:.3f} + ({b1:.3f}) × температура")
print(f"При зростанні середньомісячної температури на 1°C витрати на опалення в середньому зменшуються на {abs(b1):.3f} тис. грн ({abs(b1) * 1000:.0f} грн). Знак від'ємний — логічно: що тепліше, то менше опалювальних днів і менше витрат.")

print("\nЗавдання 2")
predicted = b0 + b1 * x
residuals = y - predicted
ss_res = (residuals ** 2).sum()
ss_tot = ((y - y.mean()) ** 2).sum()
r2_formula = 1 - ss_res / ss_tot
r2_rvalue = result.rvalue ** 2
r_p16 = pearsonr(x, y)
print(f"R² = rvalue² = {r2_rvalue:.4f}; R² = 1 − SS_res/SS_tot = {r2_formula:.4f}; збіг: {np.isclose(r2_rvalue, r2_formula)}")
print(f"r з Практики 16 = {r_p16.statistic:.4f}, r² = {r_p16.statistic ** 2:.4f}; збіг з R²: {np.isclose(r_p16.statistic ** 2, r2_rvalue)}")
print(f"Температура пояснює {r2_rvalue * 100:.1f}% розкиду витрат на опалення між місяцями; {100 - r2_rvalue * 100:.1f}% лишається непоясненим (випадковий шум витрат і нелінійність через обрізання нулем).")

print("\nЗавдання 3")
table = pd.DataFrame({"місяць": climate["місяць"], "температура": x, "фактичні": y,
                      "передбачені": predicted.round(2), "залишок": residuals.round(2)})
print(table)
fig, ax = plt.subplots(figsize=(6, 4))
ax.scatter(x, residuals)
ax.axhline(0, color="gray", linestyle="--")
ax.set_xlabel("Середньомісячна температура, °C")
ax.set_ylabel("Залишок, тис. грн")
ax.set_title("Графік залишків моделі витрат на опалення, Київ")
plt.show()
warm = climate["температура"] >= 14
print(f"Середній залишок у найтепліших місяцях (≥14°C): {residuals[warm].mean():+.3f}; у решті: {residuals[~warm].mean():+.3f}")
print(f"Передбачення для найтепліших місяців: {list(predicted[warm].round(2))}")
print("Залишки мають видиму структуру. Для червня—серпня (19–21°C) пряма передбачає від'ємні витрати (−0.04…−0.28 тис. грн), що фізично неможливо: фактичні витрати там дорівнюють 0, бо код обрізає їх через max(cost, 0), і саме тому залишки цих місяців додатні (+0.04, +0.28, +0.16). Тобто справжня залежність не пряма, а 'ламана': спадає з температурою і далі лежить на нулі. Крім того, розкид залишків нерівномірний: у теплих місяцях вони малі (до ±0.6), а в холодних і перехідних — великі (від −1.87 до +1.13). Це узгоджується з попередженням Лекції 17: R² ≈ 0.65 виглядає непогано, але не показує прихованої нелінійності — її видно лише на графіку залишків.")

print("\nЗавдання 4")
x_new = -10
y_new = b0 + b1 * x_new
print(f"Прогноз для −10°C: {y_new:.3f} тис. грн")
print(f"Спостережений діапазон температур: від {x.min()} до {x.max()} °C — значення −10°C лежить поза ним, це екстраполяція.")
print("Модель підібрана лише на температурах від −4 до 21°C. Як поводиться залежність нижче −4°C, дані нічого не кажуть: можуть діяти інші механізми (максимальна потужність котельні, тарифи, обмеження кількості днів у місяці — опалювальних днів не може бути більше 30). Тому прогноз для −10°C спирається на припущення, що лінійність зберігається, яке ніяк не перевірене, і довіра до нього нижча, ніж до прогнозу всередині діапазону.")

print("\nЗавдання 5")
print(f"p-value linregress = {result.pvalue:.6e}; p-value pearsonr = {r_p16.pvalue:.6e}")
print("Вони однакові, бо в простій регресії нахил b1 = r · (sy/sx): b1 = 0 тоді й лише тоді, коли r = 0. Обидва тести перевіряють ту саму H0 'лінійного зв'язку немає' і використовують ту саму t-статистику t = r·√(n−2)/√(1−r²) з n−2 ступенями свободи.")

