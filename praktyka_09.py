import pandas as pd

print("Практика 9. Варіант 1 — Київ, базова ціна 850 грн, базова кількість 3")

base_price = 850

print("\nЗавдання 1")
clients = pd.DataFrame([
    {"вік": 22, "дохід": 14000, "кількість": 2, "місто_доставки": "Київ"},
    {"вік": 35, "дохід": 32000, "кількість": 3, "місто_доставки": "Львів"},
    {"вік": 47, "дохід": 41000, "кількість": 4, "місто_доставки": "Київ"},
    {"вік": 29, "дохід": 25000, "кількість": 3, "місто_доставки": "Одеса"},
    {"вік": 63, "дохід": 12000, "кількість": 1, "місто_доставки": "Харків"},
    {"вік": 19, "дохід": 9000, "кількість": 2, "місто_доставки": "Київ"},
    {"вік": 54, "дохід": 38000, "кількість": 5, "місто_доставки": "Дніпро"},
    {"вік": 31, "дохід": 27000, "кількість": 3, "місто_доставки": "Львів"},
    {"вік": 41, "дохід": 52000, "кількість": 4, "місто_доставки": "Київ"},
    {"вік": 68, "дохід": 10500, "кількість": 2, "місто_доставки": "Одеса"},
])
print(clients)

print("\nЗавдання 2")
clients["сума_замовлення"] = base_price * clients["кількість"]
clients["частка_доходу"] = clients["сума_замовлення"] / clients["дохід"]
print(clients[["вік", "дохід", "кількість", "сума_замовлення", "частка_доходу"]].round(3))
print("Сума замовлення сама по собі показує лише витрати, а дохід — лише можливості. Частка доходу поєднує їх і показує, наскільки покупка відчутна для бюджету клієнта: 1700 грн для людини з доходом 9000 і з доходом 52000 — зовсім різна поведінка. Це дозволяє порівнювати клієнтів різного достатку.")

print("\nЗавдання 3")
clients["вік_cut"] = pd.cut(clients["вік"], bins=3)
clients["вік_qcut"] = pd.qcut(clients["вік"], q=3)
print(clients["вік_cut"].value_counts().sort_index())
print(clients["вік_qcut"].value_counts().sort_index())
print("cut ділить діапазон віку (19–68) на три інтервали однакової довжини, тому в групах різна кількість клієнтів — залежно від того, як вік розподілений. qcut ділить за квантилями: межі нерівні, зате в кожній групі приблизно однакова кількість клієнтів (10 не ділиться на 3 націло, тому 4/3/3).")

print("\nЗавдання 4")
for col in ["вік", "дохід"]:
    c = clients[col]
    clients[col + "_minmax"] = (c - c.min()) / (c.max() - c.min())
    clients[col + "_z"] = (c - c.mean()) / c.std()
print(clients[["вік", "дохід", "вік_minmax", "дохід_minmax", "вік_z", "дохід_z"]].head().round(3))
print("Вік вимірюється десятками років, а дохід — десятками тисяч гривень. У методах, що рахують відстані чи суми квадратів, різниця в доході на 1000 грн 'переважила' б різницю у віці на 40 років лише через масштаб одиниць. Після масштабування обидві змінні мають спільну шкалу ([0, 1] або середнє 0 і std 1) і внесок кожної порівнянний.")

print("\nЗавдання 5")
dummies = pd.get_dummies(clients["місто_доставки"], prefix="місто")
clients = pd.concat([clients, dummies], axis=1)
print(clients[["місто_доставки"] + list(dummies.columns)])
print("Нових стовпців:", dummies.shape[1], "; унікальних міст:", clients["місто_доставки"].nunique(), "; збігається:", dummies.shape[1] == clients["місто_доставки"].nunique())
print("Місто — номінальна змінна, між містами немає порядку. Кодування 1, 2, 3 вносить хибні відношення: 'Одеса = 3' буде 'більше' за 'Київ = 1', а 'Львів' — 'посередині'. One-hot створює окремий індикатор для кожного міста без жодного порядку.")

print("""
Відповіді на питання:
1. pd.cut() ділить діапазон на інтервали однакової довжини — кількість спостережень у них може сильно відрізнятися. pd.qcut() ділить за квантилями — гарантує приблизно однакову кількість спостережень у кожній групі, але межі інтервалів нерівні.
2. Номінальні категорії не мають порядку й відстаней. Числові коди 1, 2, 3 модель сприйме як упорядковані й рівновіддалені значення, що спотворить результат. One-hot подає кожну категорію окремим 0/1-стовпцем без зайвої структури.
3. Методи, що використовують відстані або штраф за величину коефіцієнтів, залежать від одиниць вимірювання: змінна з великим масштабом домінує. Масштабування вирівнює внесок змінних, і результат залежить від змісту даних, а не від вибору одиниць.
4. Похідна змінна поєднує кілька складників у показник, який прямо відповідає на змістовне питання (наскільки покупка навантажує бюджет), і робить порівнянними об'єкти різного масштабу — чого не видно, дивлячись на складники окремо.
""")
