import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

print("Практика 7. Варіант 1 — Київ, базові продажі 40 шт./день, температура 3°C")

print("\nЗавдання 1")
np.random.seed(1)
days = np.arange(1, 31)
weekend = np.isin(days % 7, [6, 0])
temperature = np.round(3 + np.random.uniform(-3, 3, size=30), 1)
sales = 40 + np.random.normal(0, 4, size=30) - (temperature - 3) * 1.5
sales = np.where(weekend, sales * np.random.uniform(1.15, 1.25, size=30), sales)
sales = np.round(sales).astype(int)
kiosk = pd.DataFrame({"день": days, "вихідний": weekend, "температура": temperature, "продажі": sales})
print(kiosk)

print("\nЗавдання 2")
fig, axes = plt.subplots(1, 2, figsize=(11, 4))
for ax, bins in zip(axes, [5, 15]):
    ax.hist(kiosk["продажі"], bins=bins, edgecolor="white")
    ax.set_xlabel("Продажі за день, шт.")
    ax.set_ylabel("Кількість днів")
    ax.set_title(f"Розподіл денних продажів, Київ (bins = {bins})")
plt.tight_layout()
plt.show()
print("bins = 5 дає змістовнішу картину: для 30 значень приблизно √30 ≈ 5–6 інтервалів, видно основну масу буднів і окрему групу вищих продажів у вихідні. bins = 15 дробить дані на стовпці з 0–3 днів, і форма губиться в шумі.")

print("\nЗавдання 3")
fig, ax = plt.subplots(figsize=(5, 4))
groups = [kiosk.loc[~kiosk["вихідний"], "продажі"], kiosk.loc[kiosk["вихідний"], "продажі"]]
ax.boxplot(groups)
ax.set_xticks([1, 2])
ax.set_xticklabels(["Будній", "Вихідний"])
ax.set_ylabel("Продажі за день, шт.")
ax.set_title("Продажі кіоску: будні проти вихідних, Київ")
plt.show()
print(f"Медіана буднів = {groups[0].median()}, вихідних = {groups[1].median()}.")
print("Медіана у вихідні помітно вища, розкид у вихідні дещо більший — це узгоджується з тим, що вихідним задано +15–25% до продажів.")

print("\nЗавдання 4")
fig, ax = plt.subplots(figsize=(5, 4))
ax.scatter(kiosk["температура"], kiosk["продажі"])
ax.set_xlabel("Температура повітря, °C")
ax.set_ylabel("Продажі за день, шт.")
ax.set_title("Продажі кіоску проти температури, Київ")
plt.show()
print(f"Кореляція: {kiosk['температура'].corr(kiosk['продажі']):.2f}")
print("Зв'язок помірний від'ємний: у холодніші дні продажі вищі. Для кіоску з напоями в холодний місяць (≈3°C) це очікувано — основний попит дають гарячі напої, а він зростає з похолоданням. Розкид великий через ефект вихідних.")

print("\nЗавдання 5")
counts, edges = np.histogram(kiosk["продажі"], bins=5)
centers = (edges[:-1] + edges[1:]) / 2
width = edges[1] - edges[0]
fig, axes = plt.subplots(1, 2, figsize=(11, 4))
axes[0].bar(centers, counts, width=width * 0.9)
axes[0].set_xlabel("Продажі за день, шт.")
axes[0].set_ylabel("Кількість днів")
axes[0].set_title("Коректно: вісь Y від нуля")
axes[0].set_ylim(0, counts.max() + 1)
axes[1].bar(centers, counts, width=width * 0.9)
axes[1].set_ylim(counts.min() - 0.5, counts.max() + 0.2)
axes[1].set_title("Спотворено: обрізана вісь Y, без підписів")
plt.tight_layout()
plt.show()
print("Застосовано обрізання осі Y (вісь починається не з нуля) і прибрано підписи осей. Висота стовпців більше не пропорційна значенням: стовпець з 1 днем майже зникає, а різниця між 4 і 5 днями виглядає в кілька разів більшою, хоча насправді це лише 1.25 раза; без підписів глядач навіть не знає, що саме відкладено на осях.")

