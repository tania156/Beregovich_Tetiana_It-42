import pandas as pd

print("Практика 6. Варіант 1 — Київ, регіон Центр")

months = ["Січ", "Лют", "Бер", "Кві", "Тра", "Чер", "Лип", "Сер", "Вер", "Жов", "Лис", "Гру"]

print("\nЗавдання 1")
kyiv = pd.Series([84, 82, 78, 70, 65, 63, 61, 63, 68, 75, 81, 85], index=months, name="вологість_%")
desc = kyiv.describe()
print(desc)
print("mean — середнє арифметичне (міра положення); std — стандартне відхилення (міра розсіювання); min і max — мінімум і максимум, їх різниця — розмах; 25% і 75% — перший і третій квартилі, їх різниця — IQR; 50% — медіана.")

print("\nЗавдання 2")
rozmakh = kyiv.max() - kyiv.min()
var1 = kyiv.var(ddof=1)
var0 = kyiv.var(ddof=0)
std = kyiv.std()
q1, q3 = kyiv.quantile([0.25, 0.75])
iqr = q3 - q1
cv = std / kyiv.mean() * 100
print(f"Розмах = {rozmakh}")
print(f"Дисперсія ddof=1 = {var1:.4f}, ddof=0 = {var0:.4f}, різниця = {var1 - var0:.4f} (у {var1 / var0:.4f} раза, тобто n/(n-1) = 12/11)")
print(f"Стандартне відхилення = {std:.4f}")
print(f"Q1 = {q1}, Q3 = {q3}, IQR = {iqr}")
print("Q1 збігається з describe:", q1 == desc["25%"], "; Q3 збігається з describe:", q3 == desc["75%"])
print(f"Коефіцієнт варіації = {cv:.2f}%")

print("\nЗавдання 3")
data = [
    ["Київ", "Центр", 84, 82, 78, 70, 65, 63, 61, 63, 68, 75, 81, 85],
    ["Львів", "Захід", 85, 83, 80, 73, 68, 65, 63, 65, 70, 77, 82, 86],
    ["Одеса", "Південь", 82, 80, 78, 74, 71, 69, 67, 68, 72, 76, 80, 83],
    ["Харків", "Схід", 83, 80, 75, 68, 62, 60, 58, 60, 66, 73, 79, 84],
    ["Дніпро", "Схід", 82, 79, 74, 67, 61, 59, 57, 59, 65, 72, 78, 83],
    ["Чернігів", "Центр", 85, 83, 79, 71, 66, 63, 61, 63, 69, 76, 82, 86],
    ["Івано-Франківськ", "Захід", 86, 84, 81, 75, 70, 67, 65, 67, 72, 78, 83, 87],
    ["Полтава", "Центр", 84, 81, 76, 69, 63, 61, 59, 61, 67, 74, 80, 85],
    ["Суми", "Схід", 85, 82, 77, 70, 64, 62, 60, 62, 68, 75, 81, 86],
    ["Ужгород", "Захід", 84, 82, 79, 73, 68, 66, 64, 66, 71, 77, 82, 85],
]
df = pd.DataFrame(data, columns=["Місто", "Регіон"] + months)
df["середня_за_рік"] = df[months].mean(axis=1)
print(df[["Місто", "Регіон", "середня_за_рік"]])
center = df[df["Регіон"] == "Центр"]["середня_за_рік"]
west = df[df["Регіон"] == "Захід"]["середня_за_рік"]
print("Центр:\n", center.describe())
print("Захід:\n", west.describe())
cv_center = center.std() / center.mean() * 100
cv_west = west.std() / west.mean() * 100
print(f"CV Центр = {cv_center:.3f}%, CV Захід = {cv_west:.3f}%")
bigger = "Центр" if center.std() > west.std() else "Захід"
print(f"Більший розкид середньої вологості між містами має регіон {bigger} (std {center.std():.3f} проти {west.std():.3f}). Середні регіонів близькі, тому висновок за CV такий самий, як за std.")

print("\nЗавдання 4")
print(f"Середнє = {kyiv.mean():.2f}, медіана = {kyiv.median()}")
print("Середнє і медіана відрізняються менш ніж на 1 відсотковий пункт, тому розподіл близький до симетричного (легка асиметрія через літній 'провал' вологості). Середнє тут репрезентативне, але медіана практично така сама, тож обидві міри коректні; середнє використовує всі значення, тому його можна обрати основним.")

print("\nЗавдання 5")
odesa = df[df["Місто"] == "Одеса"][months].iloc[0]
cv_odesa = odesa.std() / odesa.mean() * 100
print(f"CV Київ = {cv:.2f}%, CV Одеса (Південь) = {cv_odesa:.2f}%")
print("У Києві відносна мінливість вологості протягом року більша, ніж в Одесі (морський клімат згладжує сезонні коливання). CV — коректний інструмент, бо нормує розкид на рівень середнього; навіть коли середні близькі, CV робить порівняння незалежним від масштабу і є безрозмірним, тому потреба в ньому не зникає — просто висновки за std і CV тоді збігаються.")

print("""
Відповіді на питання:
1. std — стандартне відхилення (корінь із вибіркової дисперсії, ddof=1); 25% і 75% — квартилі Q1 і Q3, їх різниця — міжквартильний розмах IQR; min і max — крайні значення, їх різниця — розмах.
2. Заповнені середнім значення мають нульове відхилення від середнього: сума квадратів відхилень не змінюється, а n зростає. Наприклад, для [80, 60, NaN, 70] std = 10.0 (n=3); після заповнення 70: [80, 60, 70, 70] std = 8.16 — менше, хоча нової інформації не додалося.
3. Абсолютний std залежить від масштабу середнього: група з більшими значеннями зазвичай має більший std. CV ділить std на середнє, тож показує відносну мінливість — без нього можна хибно вважати 'варіативнішою' групу, яка просто має більші значення.
4. Розподіл вологості Києва близький до симетричного (середнє ≈ 72.92, медіана 72.5); репрезентативне середнє, але й медіана майже з ним збігається.
""")
