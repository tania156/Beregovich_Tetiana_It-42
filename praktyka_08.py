import numpy as np
import pandas as pd

print("Практика 8. Варіант 1 — Київ, середньорічна 9.5°C, амплітуда 14°C")

np.random.seed(42)
base_temp = 9.5
amplitude = 14
city = "Київ"

rows = []
for year in [2021, 2022, 2023, 2024]:
    for month in range(1, 13):
        seasonal = amplitude * np.cos((month - 7) / 12 * 2 * np.pi)
        noise = np.random.normal(0, 1.0)
        rows.append({
            "місто": city,
            "рік": year,
            "місяць": month,
            "температура": round(base_temp + seasonal + noise, 1),
        })

climate = pd.DataFrame(rows)
print(climate.head(12))
print(climate.shape)

print("\nЗавдання 1")
by_year = climate.groupby("рік")["температура"].agg(["mean", "min", "max"])
print(by_year)
print("Середні за роками відрізняються в межах кількох десятих градуса без монотонного зростання — коливання виглядають випадковими (шум), явного тренду потепління немає.")

print("\nЗавдання 2")
by_month = climate.groupby("місяць")["температура"].agg(["mean", "std"])
print(by_month)
m = by_month["std"].idxmax()
print(f"Найбільший розкид між роками — у місяці {m} (std = {by_month['std'].max():.2f}).")
print("Припущення: у реальному кліматі найнестабільніші перехідні сезони (березень—квітень, жовтень—листопад), коли погода залежить від того, чи вже встановився новий сезон. У наших синтетичних даних шум однаковий для всіх місяців, тому максимум припав на місяць випадково — це наслідок малої вибірки (4 роки).")

print("\nЗавдання 3")
pt = climate.pivot_table(index="місяць", columns="рік", values="температура", aggfunc="mean")
print(pt)
print("Зведена таблиця (місяці в рядках, роки в стовпцях) зручніша для читання людиною: одразу видно і сезонність, і порівняння років. Довга форма зручніша для groupby, фільтрації та побудови графіків — кожна змінна в окремому стовпці (tidy, Лекція 4); перехід між ними — melt/pivot.")

print("\nЗавдання 4")


def season(month):
    if month in (12, 1, 2):
        return "зима"
    elif month in (3, 4, 5):
        return "весна"
    elif month in (6, 7, 8):
        return "літо"
    return "осінь"


climate["сезон"] = climate["місяць"].apply(season)
climate["тепліше_за_середнє"] = climate["температура"] > base_temp
ct = pd.crosstab(climate["сезон"], climate["тепліше_за_середнє"])
print(ct)
print("Усі 12 літніх спостережень тепліші за 9.5°C, усі зимові — холодніші, як і очікувалося. Весна й осінь розділились: травень і вересень тепліші, березень і листопад холодніші, а квітень і жовтень мають середню температуру близьку до 9.5°C, тому розділились між категоріями залежно від року.")

print("\nЗавдання 5")
wide = climate.pivot(index="місяць", columns="рік", values="температура")
print(wide)
print("pivot() спрацював, бо кожна комбінація (місяць, рік) зустрічається рівно один раз:")
print(climate.groupby(["місяць", "рік"]).size().max())
print("Якби в місті було кілька метеостанцій (наприклад, стовпець 'станція' з двома значеннями), на одну пару місяць/рік припадало б по 2 рядки, і pivot() завершився б помилкою 'Index contains duplicate entries' — тоді потрібен pivot_table() з aggfunc.")

print("""
Відповіді на питання:
1. Split — таблиця ділиться на групи за значеннями ключа; apply — до кожної групи окремо застосовується функція (mean, std...); combine — результати збираються в нову таблицю, де індекс — ключі груп.
2. pivot() лише переставляє значення і вимагає, щоб кожна пара індекс/стовпець була унікальна; якщо їх кілька, він не знає, яке значення взяти, і падає. pivot_table() агрегує кілька значень в одне через aggfunc, тому дублікати йому не заважають.
3. crosstab() рахує частоти комбінацій двох категоріальних змінних і подає їх у вигляді таблиці. groupby([a, b]).size() дає ті самі числа, але як Series із мультиіндексом (довгий формат); crosstab одразу розкладає їх у дві осі й підставляє 0 для відсутніх комбінацій.
4. groupby і pivot_table групують за значеннями стовпців. Якщо роки чи місяці закладені в назви стовпців, вони не є значеннями змінної — групувати за ними неможливо без попереднього melt(). Довгий формат тримає кожну змінну в окремому стовпці, тож будь-яке групування чи агрегування працює однаково.
""")
