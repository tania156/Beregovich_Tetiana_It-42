import numpy as np
from scipy.optimize import linprog

print("Практика 20. Варіант 1 — Київ")

print("\nЗавдання 1")
print("""Змінні:
  x1 — кількість виробів А на тиждень, шт.
  x2 — кількість виробів Б на тиждень, шт.
Цільова функція:
  максимізувати Z = 60·x1 + 45·x2 (тижневий прибуток, грн)
Обмеження:
  3·x1 + 5·x2 <= 300 (сировина, кг)
  4·x1 + 2·x2 <= 220 (час обладнання, машино-год)
  1·x1 + 1·x2 <= 95  (електроенергія, кВт·год)
  x1 >= 0, x2 >= 0""")

c = [-60, -45]
A_ub = [
    [3, 5],
    [4, 2],
    [1, 1],
]
b_ub = [300, 220, 95]
names = ["сировина, кг", "час обладнання, год", "електроенергія, кВт·год"]


def solve(b):
    return linprog(c, A_ub=A_ub, b_ub=b, bounds=[(0, None), (0, None)], method="highs")


print("\nЗавдання 2")
res = solve(b_ub)
print("res.x =", res.x)
print("res.fun =", res.fun, "→ прибуток =", -res.fun)
print("res.status =", res.status)
print("res.message =", res.message)
print("res.status == 0:", res.status == 0, "— задачу розв'язано успішно, можна інтерпретувати.")

print("\nЗавдання 3")
x1, x2 = res.x
profit = -res.fun
print(f"Оптимально випускати {x1:g} виробів А і {x2:g} виробів Б на тиждень; максимальний тижневий прибуток — {profit:g} грн.")
if np.allclose(res.x, np.round(res.x)):
    print("Розв'язок цілочисловий, тому округлення не потрібне. Взагалі ж, якби кількості вийшли дробовими, просте округлення не гарантує найкращого цілочислового розв'язку: округлена точка може порушити обмеження (вийти за ліміт ресурсу), а округлення вниз може бути не найкращою допустимою цілою точкою. Для гарантії потрібна цілочислова оптимізація (параметр integrality у linprog або методи гілок і меж).")
else:
    print("Кількості дробові, а вироби бувають лише цілими. Просте округлення не гарантує найкращого цілочислового розв'язку: округлена точка може порушити обмеження, а округлення вниз може бути не найкращою допустимою цілою точкою. Для гарантії потрібна цілочислова оптимізація (integrality у linprog).")
    res_int = linprog(c, A_ub=A_ub, b_ub=b_ub, bounds=[(0, None), (0, None)], method="highs", integrality=[1, 1])
    print("Цілочисловий розв'язок:", res_int.x, "прибуток:", -res_int.fun)

print("\nЗавдання 4")
used = np.array(A_ub) @ res.x
for name, lim, u, s in zip(names, b_ub, used, res.slack):
    status = "АКТИВНЕ (вузьке місце)" if np.isclose(s, 0) else "неактивне, є запас"
    print(f"{name}: використано {u:g} з {lim}, slack = {s:g} → {status}")
active = [i for i, s in enumerate(res.slack) if np.isclose(s, 0)]
inactive = [i for i, s in enumerate(res.slack) if not np.isclose(s, 0)]
print(f"Вузькі місця: {', '.join(names[i] for i in active)}. Саме в розширення цих ресурсів варто інвестувати — додаткова одиниця дозволить випустити більше і підняти прибуток.")
print(f"Запас має: {', '.join(names[i] for i in inactive)}. Розширювати цей ресурс немає сенсу — він і зараз використовується не повністю, тож прибуток від цього не зросте.")

print("\nЗавдання 5")
i_act = active[0]
b_new = list(b_ub)
b_new[i_act] = b_ub[i_act] * 1.15
res_a = solve(b_new)
print(f"Активний ресурс '{names[i_act]}': ліміт {b_ub[i_act]} → {b_new[i_act]:g} (+15%)")
print(f"Було: x = {res.x}, прибуток = {profit:g}; стало: x = {np.round(res_a.x, 3)}, прибуток = {-res_a.fun:g}")
print(f"Прибуток зріс на {-res_a.fun - profit:g} грн. Співвідношення А:Б змінилося з {x1 / x2:.2f} на {res_a.x[0] / res_a.x[1]:.2f} — оптимум зсунувся вздовж іншого активного обмеження.")
print("Нові slack:", np.round(res_a.slack, 3))

i_in = inactive[0]
b_new2 = list(b_ub)
b_new2[i_in] = b_ub[i_in] * 1.5
res_b = solve(b_new2)
print(f"\nНеактивний ресурс '{names[i_in]}': ліміт {b_ub[i_in]} → {b_new2[i_in]:g} (+50%)")
print(f"Було: x = {res.x}, прибуток = {profit:g}; стало: x = {np.round(res_b.x, 3)}, прибуток = {-res_b.fun:g}")
print("Прибуток не змінився: цей ресурс і раніше мав запас, тобто не обмежував випуск. Оптимальну точку визначають активні обмеження — 'вузькі місця'; розширення ресурсу, який не є вузьким місцем, лише збільшує невикористаний запас.")

print("""
Відповіді на питання:
1. linprog реалізований як мінімізатор: шукає мінімум c·x. Максимізація Z еквівалентна мінімізації −Z, тому коефіцієнти прибутку передаємо з від'ємним знаком (c = [−60, −45]), а справжній максимальний прибуток — це −res.fun.
2. linprog приймає обмеження лише у формі A_ub·x <= b_ub. Множення нерівності на −1 змінює її знак: a·x >= b рівносильне −a·x <= −b, тому і рядок A_ub, і b_ub треба домножити на −1.
3. Активне обмеження виконується як рівність (slack = 0): ресурс витрачено повністю, і саме він не дає збільшити випуск. Неактивне має запас. Тому прибуток можна підняти лише розширенням активних ресурсів — вони і є вузькими місцями.
4. Так: збільшення активного ресурсу на 15% підняло прибуток, а збільшення неактивного на 50% нічого не змінило — повністю узгоджується з теорією.
""")
