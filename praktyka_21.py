import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

print("Практика 21. Варіант 1 — Київ, тип: площа (чверть кола), точне значення π/4")

exact = np.pi / 4
square_area = 1.0


def estimate_area(N):
    x = np.random.uniform(0, 1, N)
    y = np.random.uniform(0, 1, N)
    inside = x ** 2 + y ** 2 <= 1
    return inside.mean() * square_area


print("\nЗавдання 1")
np.random.seed(1)
N = 1000
est = estimate_area(N)
print(f"Оцінка площі чверті кола (N = {N}): {est:.4f}")

print("\nЗавдання 2")
err = abs(est - exact)
print(f"Точне значення: {exact:.4f}; абсолютна похибка: {err:.4f} ({err / exact * 100:.2f}% від точного)")
sigma = np.sqrt(exact * (1 - exact))
print(f"Очікуваний порядок похибки для N = 1000: σ/√N = {sigma / np.sqrt(N):.4f} (≈{sigma / np.sqrt(N) / exact * 100:.1f}%)")
print("Похибка близька до очікуваного порядку σ/√N — для скромного N = 1000 це нормальна точність у межах кількох відсотків, але не точність у 3–4 знаки.")

print("\nЗавдання 3")
np.random.seed(1)
rows = []
for N in [100, 1_000, 10_000, 100_000]:
    errors = []
    for _ in range(200):
        estimate = estimate_area(N)
        errors.append(abs(estimate - exact))
    rows.append({"N": N, "середня_абс_похибка": np.mean(errors)})
conv = pd.DataFrame(rows)
conv["у_скільки_разів_менша"] = conv["середня_абс_похибка"].shift(1) / conv["середня_абс_похибка"]
print(conv.round(5))
ratio_100 = conv.loc[0, "середня_абс_похибка"] / conv.loc[2, "середня_абс_похибка"]
print(f"Від N = 100 до N = 10 000 (у 100 разів більше) похибка впала в {ratio_100:.1f} раза — близько до √100 = 10, а не до 100. Кожне збільшення N у 10 разів зменшує похибку приблизно в √10 ≈ 3.2 раза.")

print("\nЗавдання 4")
fig, ax = plt.subplots(figsize=(6, 4))
ax.plot(conv["N"], conv["середня_абс_похибка"], marker="o", label="Монте-Карло")
ax.plot(conv["N"], conv.loc[0, "середня_абс_похибка"] * np.sqrt(100 / conv["N"]), linestyle="--", label="∝ 1/√N")
ax.set_xscale("log")
ax.set_xlabel("Кількість випробувань N")
ax.set_ylabel("Середня абсолютна похибка")
ax.set_title("Збіжність оцінки π/4 методом Монте-Карло, Київ")
ax.legend()
plt.show()
print("Лінія монотонно спадає і майже збігається з еталонною кривою 1/√N: кожен крок ×10 по осі N зменшує похибку приблизно в 3.2 раза. Спадання сповільнюється — щоб виграти ще один десятковий знак точності, потрібно в 100 разів більше точок.")

print("\nЗавдання 5")
print("Оцінка — це середнє N незалежних індикаторів 'точка в чверті кола' (значення 1 або 0) з математичним сподіванням π/4. Наближення оцінки до π/4 зі зростанням N гарантує закон великих чисел: вибіркове середнє незалежних однаково розподілених величин збігається до їх сподівання.")
print("Швидкість збіжності описує той самий результат Лекції 12: стандартне відхилення вибіркового середнього дорівнює σ/√N (тут σ = √(p(1−p)) ≈ 0.41), а ЦГТ каже, що похибка розподілена приблизно нормально з таким розкидом. Тому падіння похибки в ≈10 разів при зростанні N у 100 разів — це просто властивість вибіркового середнього, а не окрема особливість методу Монте-Карло.")

