import numpy as np
import pandas as pd

print("Практика 4. Варіант 1 — Київ, базова ціна 850 грн, базова кількість 3")

print("\nЗавдання 1")
orders = pd.DataFrame([
    {"id": 1, "дата": "2026-09-01", "місто": "Київ", "ціна": 850, "кількість": 3},
    {"id": 2, "дата": "2026-09-02", "місто": " Київ ", "ціна": "860 грн", "кількість": np.nan},
    {"id": 3, "дата": "2026-09-03", "місто": "КИЇВ", "ціна": 840, "кількість": 4},
    {"id": 4, "дата": "2026-09-04", "місто": "Київ", "ціна": "845 грн", "кількість": 2},
    {"id": 5, "дата": "2026-09-05", "місто": "Київ", "ціна": 8500, "кількість": 3},
    {"id": 6, "дата": "2026-09-06", "місто": " Київ ", "ціна": 855, "кількість": np.nan},
    {"id": 7, "дата": "2026-09-07", "місто": "КИЇВ", "ціна": 850, "кількість": 3},
    {"id": 7, "дата": "2026-09-07", "місто": "КИЇВ", "ціна": 850, "кількість": 3},
])
print(orders)
print(orders.dtypes)

print("\nЗавдання 2")
print(orders.isna().sum())
orders["кількість"] = orders["кількість"].fillna(orders["кількість"].median())
print(orders)
print("Медіана стійка до викидів і на 8 спостереженнях не зсувається одним нетиповим значенням; середнє з таким малим набором легко спотворити, а заповнення ним штучно зменшує розкид.")

print("\nЗавдання 3")
print("Повні дублікати:", orders.duplicated().sum())
print("Дублікати за id і датою:", orders.duplicated(subset=["id", "дата"]).sum())
orders = orders.drop_duplicates(subset=["id", "дата"]).reset_index(drop=True)
print("Рядків залишилось:", len(orders))

print("\nЗавдання 4")
orders["ціна"] = orders["ціна"].astype(str).str.replace(" грн", "", regex=False).astype(float)
print(orders.dtypes)
orders["місто"] = orders["місто"].str.strip().str.lower().replace({"київ": "Київ"})
print(orders["місто"].unique())

print("\nЗавдання 5")
q1, q3 = orders["ціна"].quantile([0.25, 0.75])
iqr = q3 - q1
lower, upper = q1 - 1.5 * iqr, q3 + 1.5 * iqr
print(f"Q1 = {q1}, Q3 = {q3}, IQR = {iqr}, межі: [{lower}, {upper}]")
print(orders[(orders["ціна"] < lower) | (orders["ціна"] > upper)])
print("Ціна 8500 грн рівно в 10 разів більша за базову при звичайній кількості 3 шт. — це схоже на зайвий нуль при введенні, тому вважаю це помилкою вводу і виправляю на 850. Великим замовленням це бути не може: ціна — за одиницю товару, а кількість не зросла.")
orders.loc[orders["ціна"] > upper, "ціна"] = orders.loc[orders["ціна"] > upper, "ціна"] / 10
print(orders)

print("""
Відповіді на питання:
1. Заповнення середнім ставить кілька однакових значень точно в центр розподілу; їхні відхилення від середнього нульові, тож сума квадратів відхилень не зростає, а n зростає — стандартне відхилення штучно зменшується.
2. duplicated() без subset шукає повний збіг усіх стовпців; із subset — збіг лише вказаних полів. Рядки, що відрізняються в іншому полі (наприклад, у записі міста), без subset не вважаються дублікатами, а із subset — вважаються.
3. Значення поза IQR може бути реальним рідкісним явищем (велике замовлення, аномальна погода). Автоматичне видалення втрачає справжню інформацію та зміщує статистики; рішення треба приймати за змістом даних.
""")
