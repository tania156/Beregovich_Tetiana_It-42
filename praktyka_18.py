import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import statsmodels.api as sm
from scipy import stats
from statsmodels.stats.outliers_influence import variance_inflation_factor

print("Практика 18. Варіант 1 — Київ, 9.5°C, амплітуда 14°C, базова вологість 74%")

alpha = 0.05
np.random.seed(42)
city = "Київ"
mean_temp = 9.5
amplitude = 14
hum_base = 74

rows = []
for month in range(1, 13):
    temp = mean_temp + amplitude * np.cos((month - 7) / 12 * 2 * np.pi) + np.random.normal(0, 1.0)
    humidity = hum_base + np.random.normal(0, 5.0)
    if temp < 8:
        opal_days = 30
    elif temp < 12:
        opal_days = 15
    else:
        opal_days = 0

    cost = (
        200
        - 9.0 * temp
        + 0.6 * humidity
        + 2.5 * opal_days
        + np.random.normal(0, 15)
    )
    rows.append({
        "місто": city, "місяць": month,
        "температура": round(temp, 1),
        "вологість": round(humidity, 1),
        "опалювальні_дні": opal_days,
        "витрати_на_опалення": round(cost, 1),
    })

heating = pd.DataFrame(rows)
print(heating)
y = heating["витрати_на_опалення"]


def vif_table(X):
    return {col: round(variance_inflation_factor(X.values, i), 2) for i, col in enumerate(X.columns) if col != "const"}


print("\nЗавдання 1")
X2 = sm.add_constant(heating[["температура", "вологість"]])
model2 = sm.OLS(y, X2).fit()
print(model2.summary())
print(f"R² = {model2.rsquared:.4f}, adjusted R² = {model2.rsquared_adj:.4f}")

print("\nЗавдання 2")
bt, bh = model2.params["температура"], model2.params["вологість"]
pt, ph = model2.pvalues["температура"], model2.pvalues["вологість"]
print(f"температура: за незмінної вологості кожен додатковий градус середньомісячної температури змінює витрати на опалення на {bt:.2f} умовних одиниць (зменшує на {abs(bt):.2f}). P>|t| = {pt:.4f} → {'значущий' if pt < alpha else 'не значущий'} при α = 0.05.")
print(f"вологість: за незмінної температури кожен додатковий відсоток вологості змінює витрати на {bh:+.2f} умовних одиниць. P>|t| = {ph:.4f} → {'значущий' if ph < alpha else 'не значущий'} при α = 0.05.")
if ph >= alpha:
    print("У коді генерації вологість впливає на витрати (0.6 на 1%), але цей ефект малий порівняно з шумом (σ = 15) і розкидом вологості (σ = 5) — на 12 спостереженнях його не вдається статистично виявити.")

print("\nЗавдання 3")
vif2 = vif_table(X2)
print(vif2)
print("Обидва VIF ≈ 1.55 — нижче порогу 5, проблеми мультиколінеарності немає. У коді генерації вологість = базова вологість + випадковий шум і від температури не залежить. Помірна вибіркова кореляція між ними (≈ −0.6) — випадковий збіг на лише 12 точках, а не закладений у дані зв'язок; на більшій вибірці вона прямувала б до нуля.")
print(f"Кореляція температура—вологість: {heating['температура'].corr(heating['вологість']):.3f}")

print("\nЗавдання 4")
X3 = sm.add_constant(heating[["температура", "вологість", "опалювальні_дні"]])
model3 = sm.OLS(y, X3).fit()
print(model3.summary().tables[1])
comparison = pd.DataFrame({
    "модель": ["2 предиктори", "3 предиктори"],
    "R²": [model2.rsquared, model3.rsquared],
    "adjusted R²": [model2.rsquared_adj, model3.rsquared_adj],
})
print(comparison.round(4))
vif3 = vif_table(X3)
print("VIF трипредикторної моделі:", vif3)
gain = model3.rsquared_adj - model2.rsquared_adj
if gain > 0:
    print(f"Adjusted R² зріс на {gain:.4f}: опалювальні дні додали пояснювальної сили більше, ніж штраф за ступінь свободи. Це логічно — у коді витрати прямо залежать від опалювальних днів (+2.5 на день), і ця залежність ступінчаста, тобто не повністю відтворюється лінійним членом температури.")
else:
    print(f"Adjusted R² не зріс ({gain:+.4f}): доданий предиктор не виправдав штрафу.")
print(f"Однак VIF температури і опалювальних днів ({vif3['температура']} і {vif3['опалювальні_дні']}) вказують на сильний зв'язок між ними — обидва породжені тією самою сезонною хвилею. Через це окремі коефіцієнти трипредикторної моделі нестабільні та гірше інтерпретуються (ширші довірчі інтервали). Висновок: якщо мета — прогноз, третій предиктор виправданий; якщо мета — інтерпретувати ефект температури 'за інших рівних умов', краще модель з двома предикторами або обережна інтерпретація.")

print("\nЗавдання 5")
fitted = model2.fittedvalues
resid = model2.resid
fig, axes = plt.subplots(1, 2, figsize=(11, 4))
axes[0].scatter(fitted, resid)
axes[0].axhline(0, color="red", linestyle="--")
axes[0].set_xlabel("Передбачені витрати, умов. од.")
axes[0].set_ylabel("Залишок, умов. од.")
axes[0].set_title("Залишки проти передбачених значень")
stats.probplot(resid, dist="norm", plot=axes[1])
axes[1].set_title("QQ-plot залишків")
plt.tight_layout()
plt.show()
low_half = resid[fitted <= fitted.median()]
high_half = resid[fitted > fitted.median()]
print(f"std залишків у нижній половині передбачень = {low_half.std():.2f}, у верхній = {high_half.std():.2f}")
print("Класичної лійки (розкид, що монотонно зростає чи звужується з передбаченням) немає. Розкид у нижній половині передбачень (теплі місяці) приблизно вдвічі більший, але це пов'язано не з величиною витрат, а з тим, що модель не має ступінчастого члена опалювальних днів: травень і вересень (16–17°C, вже без опалення) модель переоцінює (−30, −28), а липень недооцінює (+36). На 12 точках це радше ознака пропущеного предиктора, ніж гетероскедастичності, — що й підтверджує Завдання 4.")
sw_stat, sw_p = stats.shapiro(resid)
print(f"Шапіро-Вілк: W = {sw_stat:.4f}, p = {sw_p:.4f}")
if sw_p >= alpha:
    print("p ≥ 0.05 → немає підстав відхилити нормальність залишків; точки QQ-plot лежать близько до прямої, p-value коефіцієнтів можна вважати достовірними.")
else:
    print("p < 0.05 → залишки значуще відхиляються від нормального розподілу; p-value і довірчі інтервали коефіцієнтів треба трактувати з обережністю.")

print("\nЗавдання 6")
X1 = sm.add_constant(heating[["температура"]])
model1 = sm.OLS(y, X1).fit()
print(f"Проста регресія (лише температура): R² = {model1.rsquared:.4f}")
print(f"Множинна (температура + вологість): R² = {model2.rsquared:.4f}, adjusted R² = {model2.rsquared_adj:.4f}")
diff = model2.rsquared_adj - model1.rsquared
print(f"Різниця adjusted R² множинної і R² простої: {diff:+.4f}")
print("Звичайний R² при додаванні вологості не може зменшитись — МНК у гіршому разі обнулив би її коефіцієнт. Але приріст мізерний, бо температура вже пояснює майже всю сезонну мінливість витрат, а внесок вологості малий і тоне в шумі. Після штрафу за додатковий предиктор adjusted R² практично не кращий (або гірший) за R² простої моделі — вологість не додала змістовної пояснювальної сили.")

print("""
Відповіді на питання:
1. sm.OLS не додає вільний член автоматично. sm.add_constant() додає стовпець одиниць, коефіцієнт при якому і є b0. Без нього модель примусово проходить через початок координат: коефіцієнти зміщуються, а R² рахується відносно нуля і може бути оманливо високим.
2. Коефіцієнт множинної регресії — це ефект предиктора за незмінних інших предикторів (частинна похідна). Коефіцієнт простої регресії включає і власний ефект предиктора, і ефекти пов'язаних із ним змінних, яких немає в моделі, тому при корельованих предикторах ці числа різні.
3. Стара модель — окремий випадок нової з нульовим коефіцієнтом при новому предикторі, тому МНК з новим предиктором ніколи не дасть більшу суму квадратів залишків. R² не зменшується навіть від шуму, тож модель із більшою кількістю предикторів завжди 'виграє' — порівнювати слід adjusted R², який штрафує за кожен предиктор.
4. VIF ≈ 1 — предиктор практично не пояснюється іншими, його коефіцієнт оцінюється стабільно. VIF > 10 — предиктор майже лінійно виражається через інші, дисперсія його коефіцієнта роздута, оцінки нестабільні. На практиці прибирають один із корельованих предикторів, об'єднують їх в один показник або, якщо мета лише прогноз, залишають як є.
""")
